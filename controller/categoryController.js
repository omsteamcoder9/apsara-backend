// ✅ Delete file from R2
const deleteFile = async (filePath) => {
    if (!filePath) return false;
    try {
        // Check if it's an R2 URL
        if (filePath.startsWith('http://') || filePath.startsWith('https://')) {
            console.log(`🗑️ Deleting from R2: ${filePath}`);
            const result = await deleteFileFromR2(filePath);
            return result.success;
        }
        
        // For backward compatibility - local file deletion
        const fullPath = path.join(process.cwd(), filePath);
        if (fs.existsSync(fullPath)) {
            fs.unlinkSync(fullPath);
            console.log(`✅ Deleted: ${filePath}`);
            return true;
        }
        return false;
    } catch (error) {
        console.error('❌ Error deleting file:', error);
        return false;
    }
};

// ✅ 1. CREATE CATEGORY
export const createCategory = async (req, reply) => {
    const { 
        name, 
        description, 
        parent, 
        status, 
        featured, 
        metaTitle, 
        metaDescription, 
        metaKeywords, 
        displayOrder,
        existingImagePath // ✅ Reuse image from preview
    } = req.body;

    if (!name || !name.trim()) {
        throw new ValidationError('Category name is required', {
            field: 'name',
            required: true
        });
    }

    const existingCategory = await Category.findOne({ name: name.trim() });
    if (existingCategory) {
        throw new ConflictError('Category with this name already exists', {
            name: name.trim()
        });
    }

    // ✅ Handle image - priority: uploaded file > existingImagePath (from preview) > null
    let imagePath = null;
    
    if (req.uploadedFile) {
        // User uploaded an image
        imagePath = await saveUploadedFileToR2(req.uploadedFile);
        console.log('📷 Using uploaded image (R2)');
    } else if (existingImagePath) {
        // ✅ Use the image from preview (no new generation)
        imagePath = existingImagePath;
        console.log('📷 Using existing preview image:', imagePath);
    } else {
        console.log('📷 No image provided');
    }

    const slug = slugify(name.trim(), { lower: true, strict: true });
    let finalSlug = slug;
    let counter = 1;
    while (await Category.findOne({ slug: finalSlug })) {
        finalSlug = `${slug}-${counter}`;
        counter++;
    }

    // ✅ Auto-generate description if not provided
    let finalDescription = description || '';
    let finalMetaTitle = metaTitle || '';
    let finalMetaDescription = metaDescription || '';
    let parsedMetaKeywords = [];

    if (!description && !metaTitle && !metaDescription && !metaKeywords) {
        console.log(`🔄 Generating content for category: ${name.trim()}`);
        const generated = await generateDescriptionWithGemini(name.trim());
        finalDescription = generated.description;
        finalMetaTitle = generated.metaTitle;
        finalMetaDescription = generated.metaDescription;
        parsedMetaKeywords = generated.metaKeywords;
    } else {
        // Parse metaKeywords if provided
        if (metaKeywords) {
            if (Array.isArray(metaKeywords)) {
                parsedMetaKeywords = metaKeywords;
            } else if (typeof metaKeywords === 'string') {
                parsedMetaKeywords = metaKeywords.split(',').map(k => k.trim()).filter(Boolean);
            }
        }
    }

    const category = new Category({
        name: name.trim(),
        slug: finalSlug,
        description: finalDescription,
        parent: parent || null,
        image: imagePath,
        status: status || 'active',
        featured: featured === 'true' || featured === true,
        metaTitle: finalMetaTitle || name.trim(),
        metaDescription: finalMetaDescription || `Shop the best ${name.trim()} at great prices.`,
        metaKeywords: parsedMetaKeywords,
        displayOrder: parseInt(displayOrder) || 0,
        createdBy: req.user.id
    });

    await category.save();

    reply.status(201).send({
        success: true,
        message: 'Category created successfully',
        data: category
    });
};

