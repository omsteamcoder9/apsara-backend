// ✅ 5. UPDATE CATEGORY
export const updateCategory = async (req, reply) => {
    const { id } = req.params;

    if (!mongoose.Types.ObjectId.isValid(id)) {
        throw new ValidationError('Invalid category ID', {
            field: 'id',
            received: id
        });
    }

    const category = await Category.findById(id);
    if (!category) {
        throw new NotFoundError('Category', { id });
    }

    const { 
        name, 
        description, 
        parent, 
        status, 
        featured, 
        metaTitle, 
        metaDescription, 
        metaKeywords, 
        displayOrder, 
        deleteImage,
        existingImagePath // ✅ Reuse image from preview
    } = req.body;

    // ✅ Handle image deletion
    if (deleteImage === 'true' || deleteImage === true) {
        if (category.image) {
            await deleteFile(category.image);
            category.image = null;
        }
    }

    // ✅ Handle new image (replaces old) - priority: uploaded > existingImagePath
    if (req.uploadedFile) {
        // User uploaded a new image
        if (category.image) {
            await deleteFile(category.image);
        }
        category.image = await saveUploadedFileToR2(req.uploadedFile);
        console.log('📷 Using uploaded image (R2)');
    } else if (existingImagePath) {
        // ✅ Use the image from preview (no new generation)
        if (category.image) {
            await deleteFile(category.image);
        }
        category.image = existingImagePath;
        console.log('📷 Using existing preview image:', existingImagePath);
    }

    // ✅ Update fields with auto-generation if name changes and fields are empty
    if (name && name.trim()) {
        category.name = name.trim();
        
        // Auto-generate if description, meta fields are empty
        if (!description && !metaTitle && !metaDescription && !metaKeywords) {
            console.log(`🔄 Regenerating content for updated category: ${name.trim()}`);
            const generated = await generateDescriptionWithGemini(name.trim());
            category.description = generated.description;
            category.metaTitle = generated.metaTitle;
            category.metaDescription = generated.metaDescription;
            
            if (generated.metaKeywords.length > 0) {
                category.metaKeywords = generated.metaKeywords;
            }
        }
        
        const slug = slugify(name.trim(), { lower: true, strict: true });
        let finalSlug = slug;
        let counter = 1;
        while (await Category.findOne({ slug: finalSlug, _id: { $ne: id } })) {
            finalSlug = `${slug}-${counter}`;
            counter++;
        }
        category.slug = finalSlug;
    }

    // Update other fields (if provided, they override auto-generated content)
    if (description !== undefined && description.trim()) {
        category.description = description;
    }
    if (parent !== undefined) category.parent = parent === 'null' ? null : parent;
    if (status) category.status = status;
    if (featured !== undefined) category.featured = featured === 'true' || featured === true;
    if (metaTitle !== undefined && metaTitle.trim()) {
        category.metaTitle = metaTitle;
    }
    if (metaDescription !== undefined && metaDescription.trim()) {
        category.metaDescription = metaDescription;
    }
    if (displayOrder !== undefined) category.displayOrder = parseInt(displayOrder) || 0;

    if (metaKeywords !== undefined) {
        if (Array.isArray(metaKeywords)) {
            category.metaKeywords = metaKeywords;
        } else if (typeof metaKeywords === 'string' && metaKeywords.trim()) {
            category.metaKeywords = metaKeywords.split(',').map(k => k.trim()).filter(Boolean);
        }
    }

    await category.save();

    reply.status(200).send({
        success: true,
        message: 'Category updated successfully',
        data: category
    });
};

// ✅ 6. DELETE CATEGORY
export const deleteCategory = async (req, reply) => {
    const { id } = req.params;

    if (!mongoose.Types.ObjectId.isValid(id)) {
        throw new ValidationError('Invalid category ID', {
            field: 'id',
            received: id
        });
    }

    const category = await Category.findById(id);
    if (!category) {
        throw new NotFoundError('Category', { id });
    }

    const subcategories = await Category.find({ parent: id });
    if (subcategories.length > 0) {
        throw new BusinessLogicError(
            `Cannot delete category with ${subcategories.length} subcategory(s)`,
            {
                subcategoriesCount: subcategories.length,
                subcategories: subcategories.map(s => s.name)
            }
        );
    }

    const productsCount = await Product.countDocuments({ category: id });
    if (productsCount > 0) {
        throw new BusinessLogicError(
            `Cannot delete category with ${productsCount} product(s)`,
            {
                productsCount: productsCount,
                categoryId: id
            }
        );
    }

    if (category.image) {
        await deleteFile(category.image);
    }

    await Category.findByIdAndDelete(id);

    reply.status(200).send({
        success: true,
        message: 'Category deleted successfully'
    });
};

// ✅ 7. GET CATEGORIES TREE
export const getCategoriesTree = async (req, reply) => {
    const categories = await Category.find({ status: 'active' }).sort('displayOrder name');
    
    const categoryMap = {};
    const roots = [];

    categories.forEach(category => {
        categoryMap[category._id] = { ...category.toObject(), children: [] };
    });

    categories.forEach(category => {
        if (category.parent && categoryMap[category.parent]) {
            categoryMap[category.parent].children.push(categoryMap[category._id]);
        } else {
            roots.push(categoryMap[category._id]);
        }
    });

    reply.status(200).send({
        success: true,
        data: roots
    });
};

// ✅ 8. GET CATEGORY PRODUCTS
export const getCategoryProducts = async (req, reply) => {
    const { id } = req.params;
    const { page = 1, limit = 12, sortBy = 'createdAt', sortOrder = 'desc' } = req.query;

    if (!mongoose.Types.ObjectId.isValid(id)) {
        throw new ValidationError('Invalid category ID', {
            field: 'id',
            received: id
        });
    }

    const category = await Category.findById(id);
    if (!category) {
        throw new NotFoundError('Category', { id });
    }

    const subcategories = await Category.find({ parent: id, status: 'active' });
    const categoryIds = [id, ...subcategories.map(sub => sub._id)];

    const skip = (parseInt(page) - 1) * parseInt(limit);
    const sortConfig = { [sortBy]: sortOrder === 'desc' ? -1 : 1 };

    const [products, totalCount] = await Promise.all([
        Product.find({ category: { $in: categoryIds }, status: 'active' })
            .populate('category', 'name slug')
            .sort(sortConfig)
            .skip(skip)
            .limit(parseInt(limit))
            .lean(),
        Product.countDocuments({ category: { $in: categoryIds }, status: 'active' })
    ]);

    reply.status(200).send({
        success: true,
        category: { _id: category._id, name: category.name, slug: category.slug },
        data: products,
        pagination: {
            currentPage: parseInt(page),
            totalPages: Math.ceil(totalCount / parseInt(limit)),
            totalProducts: totalCount,
            hasNext: skip + products.length < totalCount,
            hasPrev: parseInt(page) > 1
        }
    });
};